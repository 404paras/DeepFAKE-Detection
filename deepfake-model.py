class DeepfakeDetector(nn.Module):
    def __init__(self, num_classes=2):
        super().__init__()

        # CNN Feature Extractor (ResNeXt50)
        base_model = models.resnet50(pretrained=True)
        self.cnn = nn.Sequential(*list(base_model.children())[:-2])
        self.avgpool = nn.AdaptiveAvgPool2d(1)

        # Temporal Modeling (BiGRU)
        self.gru = nn.GRU(
            input_size=2048,
            hidden_size=1024,
            num_layers=2,  #  Try reducing to 1 layer
            bidirectional=True,
            batch_first=True,
            dropout=0.2      #  Slightly reduced dropout
        )

        # Attention Mechanism
        self.attention = nn.MultiheadAttention(
            embed_dim=2048,  # 1024*2 (bidirectional)
            num_heads=8,
            dropout=0.4,      #  Slightly reduced dropout
            batch_first=True
        )

        # Classification Head
        self.classifier = nn.Sequential(
            nn.LayerNorm(2048),
            nn.Dropout(0.4),      #  Adjusted dropout
            nn.Linear(2048, 512),
            nn.GELU(),
            nn.Dropout(0.4),      #  Adjusted dropout
            nn.Linear(512, num_classes)
        )

    def forward(self, x):
        batch_size, seq_len, c, h, w = x.shape

        # CNN Features
        x = x.view(batch_size*seq_len, c, h, w)
        x = self.cnn(x)
        x = self.avgpool(x)
        x = x.view(batch_size, seq_len, -1)

        # BiGRU
        gru_out, _ = self.gru(x)

        # Attention
        attn_out, _ = self.attention(gru_out, gru_out, gru_out)
        context = gru_out + attn_out  # Residual connection

        # Classification
        context = torch.mean(context, dim=1)
        return self.classifier(context)

