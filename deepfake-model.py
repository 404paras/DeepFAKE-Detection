def print_confusion_matrix(y_true, y_pred):
    cm = confusion_matrix(y_true, y_pred)

    print('True Negative (Fake predicted as Fake): ', cm[0][0])
    print('False Positive (Fake predicted as Real): ', cm[0][1])
    print('False Negative (Real predicted as Fake): ', cm[1][0])
    print('True Positive (Real predicted as Real): ', cm[1][1])
    print('\n')

    labels = ['Fake', 'Real']
    df_cm = pd.DataFrame(cm, index=labels, columns=labels)

    sn.set(font_scale=1.2)
    sn.heatmap(df_cm, annot=True, fmt='d', cmap="magma", annot_kws={"size": 14})
    plt.ylabel('Actual label', fontsize=16)
    plt.xlabel('Predicted label', fontsize=16)
    plt.xticks(fontsize=12)
    plt.yticks(fontsize=12, rotation=0)
    plt.tight_layout()
    plt.show()

    acc = (cm[0][0] + cm[1][1]) / np.sum(cm)
    print(f"Calculated Accuracy: {acc * 100:.2f}%")

